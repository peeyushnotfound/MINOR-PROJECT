CREATE TABLE director (
    director_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    date_of_birth DATE
);

CREATE TABLE actor (
    actor_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    gender CHAR(1) CHECK (gender IN ('M', 'F', 'O')),
    date_of_birth DATE
);

CREATE TABLE genre (
    genre_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_name VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE movie (
    movie_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(150) NOT NULL,
    release_year NUMBER(4) NOT NULL CHECK (release_year BETWEEN 1900 AND 2100),
    duration NUMBER(4) NOT NULL CHECK (duration > 0),
    director_id NUMBER NOT NULL,
    CONSTRAINT fk_movie_director
        FOREIGN KEY (director_id) REFERENCES director(director_id)
);

CREATE TABLE act_in (
    actor_id NUMBER NOT NULL,
    movie_id NUMBER NOT NULL,
    CONSTRAINT pk_act_in PRIMARY KEY (actor_id, movie_id),
    CONSTRAINT fk_act_in_actor FOREIGN KEY (actor_id) REFERENCES actor(actor_id),
    CONSTRAINT fk_act_in_movie FOREIGN KEY (movie_id) REFERENCES movie(movie_id)
);

CREATE TABLE belongs_to (
    movie_id NUMBER NOT NULL,
    genre_id NUMBER NOT NULL,
    CONSTRAINT pk_belongs_to PRIMARY KEY (movie_id, genre_id),
    CONSTRAINT fk_belongs_to_movie FOREIGN KEY (movie_id) REFERENCES movie(movie_id),
    CONSTRAINT fk_belongs_to_genre FOREIGN KEY (genre_id) REFERENCES genre(genre_id)
);

